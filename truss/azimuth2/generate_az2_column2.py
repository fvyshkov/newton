#!/usr/bin/env python3
"""Колонна энкодера v2 — под РЕАЛЬНУЮ плату AS5048A (гимбальный клон, обмер штангелем
2026-07-14): круглая с двумя спрямлёнными кромками, 15.45 мм между спрямлениями,
2 отверстия Ø2.0 с межцентровым 11.79 мм, чип TSSOP по центру между отверстиями.

Вместо 4 столбиков-бобышек (не совпали с платой) — ПЛОЩАДКА С 2 ШТЫРЬКАМИ:
плата надевается отверстиями на штырьки, гравитация + позже капля клея/скотч.
Центровка чипа на ось — сдвигом ВСЕЙ колонны: отверстия башмака к фанере
расточены до Ø6 (M4 + шайба → юстировка ±1 мм во все стороны).

Ориентация: линия штырьков — вдоль Y; сторона проводов платы получается по -X,
при установке крути колонну как удобно ДО затяжки M4.

Стек по Z (z=0 фанера): чип должен встать верхом на CHIP_TOP_Z=15.5 (зазор 1.2
до магнита на 16.7). Верх площадки = 15.5 − чип 1.1 − плата 1.6 = 12.8.
Если реальная толщина платы не 1.6 — поправить BOARD_T и перегенерить.
"""
import numpy as np
import trimesh

import generate_az2 as A

# ---- обмер платы (штангель пользователя, 2026-07-14) ----
BOARD_FLATS = 15.45     # между спрямлёнными кромками
HOLE_PITCH = 11.79      # межцентровое отверстий
HOLE_D = 2.0            # диаметр отверстий платы
STACK_H = 2.58          # низ платы → верх ЧИПА (штангель плашмя через чип)

PIN_D = 1.7             # штырёк: печать полнеет ~+0.15 → ~1.85 в дырку 2.0
PIN_H = 5.5             # НАМЕРЕННО длинные (ловят плату и с подкладками);
                        # перед финальной сборкой ПОДРЕЗАТЬ до ~3 мм над площадкой,
                        # иначе цепляют ступицу спайдера (низ ступицы z17)
PLAT_D = 17.0           # диск площадки (меньше платы — кромки и пады висят)
PLAT_T = 3.0

# Площадка НАМЕРЕННО занижена на 0.5: недостающую высоту добирать подкладками
# под плату (проще, чем пилить). Номинал: зазор чип-магнит 1.7 вместо 1.2;
# худший случай (магнит сидит глубже) всё равно в рабочем диапазоне.
LOW_MARGIN = 0.5
PLAT_TOP = A.CHIP_TOP_Z - STACK_H - LOW_MARGIN   # 15.5-2.58-0.5 = 12.42
COL_D = 40.0
FOOT_D = 70.0
FOOT_T = 6.0
FOOT_HOLE = 6.0         # юстировочные (M4+шайба, ход ±1)
FOOT_HOLE_R = 28.0


def column2():
    solids = [
        A.cyl(FOOT_D / 2, FOOT_T, T=A.tr(0, 0, FOOT_T / 2)),                 # башмак
        A.cyl(COL_D / 2, PLAT_TOP - PLAT_T, T=A.tr(0, 0, (PLAT_TOP - PLAT_T) / 2)),
        A.cyl(PLAT_D / 2, PLAT_T, T=A.tr(0, 0, PLAT_TOP - PLAT_T / 2)),      # площадка
    ]
    # 2 штырька вдоль Y ±HOLE_PITCH/2, с конусом-заходом сверху
    for sy in (-1, 1):
        y = sy * HOLE_PITCH / 2
        solids.append(A.cyl(PIN_D / 2, PIN_H - 0.8, seg=32,
                            T=A.tr(0, y, PLAT_TOP + (PIN_H - 0.8) / 2)))
        cone = trimesh.creation.cone(radius=PIN_D / 2, height=0.8, sections=32)
        cone.apply_translation([0, y, PLAT_TOP + PIN_H - 0.8])
        solids.append(cone)
    part = trimesh.boolean.union(solids)

    cuts = []
    for ang in (90, 210, 330):                       # юстировочные к фанере
        a = np.radians(ang)
        cuts.append(A.cyl(FOOT_HOLE / 2, FOOT_T + 2, seg=32,
                          T=A.tr(FOOT_HOLE_R * np.cos(a), FOOT_HOLE_R * np.sin(a),
                                 FOOT_T / 2)))
    part = part.difference(cuts)

    # ---- проверки ----
    assert HOLE_PITCH / 2 + PIN_D / 2 < PLAT_D / 2, "штырёк вылез за площадку"
    chip_top = PLAT_TOP + STACK_H
    gap = A.MAG_FACE_Z - chip_top
    assert 0.8 <= gap <= 2.5, f"зазор чип-магнит {gap:.2f} вне рабочего диапазона"
    pin_top = PLAT_TOP + PIN_H
    print(f"  стек: площадка {PLAT_TOP:.2f} + плата/чип {STACK_H} → чип {chip_top:.2f};"
          f" магнит {A.MAG_FACE_Z} → зазор {gap:.2f} (добирать подкладками под плату)")
    print(f"  штырьки: Ø{PIN_D} на ±{HOLE_PITCH/2} по Y, верх {pin_top:.1f} —"
          f" ⚠ ДЛИННЫЕ намеренно: подрезать до ~{PLAT_TOP+3:.0f} (ступица спайдера на 17)")
    return A.finish(part, "az2_encoder_column_pins")


if __name__ == "__main__":
    print("Колонна энкодера v2 (штырьки под реальную плату)…")
    column2()
    print("Печать: как стоит (штырьками вверх), PETG, без поддержек.")
    print("Сборка: плату на штырьки (чипом вверх, провода свесить с края),")
    print("колонну на фанеру M4+шайбы НЕ затягивая — юстировка по веб-центровке,")
    print("затянуть после ✅. Зазор добирать подкладками ПОД плату (шайба/PET),")
    print("штырьки подрезать кусачками перед финальной сборкой.")
