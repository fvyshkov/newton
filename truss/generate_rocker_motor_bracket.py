"""
Кронштейн азимутального привода (belt-offset, 42:1) — крепится 4×M4 к плоской
площадке приводного угла (Rocker_corner_drive, узел 270°), угол НЕ трогаем.

Почему ремень, а не прямой мотор (см. геометрию, подтверждена 3 источниками):
  • площадка z=83, зубья венца z=50..60 → провал 28 мм; вал NEMA17 ~22 мм НЕ достаёт.
  • мотор соосно с шестернёй (0,−240) бьётся о площадку/обод венца.
Решение: мотор уезжает внутрь (0,−181.4) и вверх; вниз к зубьям привод спускает
Ø8 вал на 2×608ZZ, соединённый ремнём GT2 20T→60T (3:1). Шестерня 16T=14:1 → 42:1.

Мировые координаты (как в gen_rocker_comic): z=0 верх земли, +Y к центру азимута,
угол 270° на −Y. Ось шестерни (0,−240), ось мотора (0,−181.4).

Стек Z по оси шестерни (0,−240):
  50..62  шестерня 16T (уже напечатана Rocker_pinion_16T), центр 56 в зубьях венца
  64..76  шкив 60T (Ø40) — в окне Ø40 площадки; плоскость ремня z=70
  79..86  нижний 608ZZ
  89..96  верхний 608ZZ
Мотор (0,−181.4): фланец z≈86, корпус вверх; вал вниз, шкив 20T на z64..76.

Печатаем ОДНУ деталь. Остальное — покупное/уже есть (2×608ZZ, Ø8 вал, шкивы, ремень).
Компенсация неровности сегментного венца: 4 радиальные ПРОРЕЗИ под M4 → двигаешь
всю каретку по Y, ставишь зазор зацепления, затягиваешь. (Пружину — опционально, v2.)
"""
import numpy as np
import trimesh
from pathlib import Path

OUT = Path(__file__).parent / "print_queue" / "motor_kron" / "Rocker_motor_bracket.stl"

# ---------- интерфейсы (из свёрстанного спека) ----------
PINION_XY = (0.0, -240.0)      # ось шестерни/вала = межцентр 224+16
# Мотор сдвинут ВНУТРЬ к −Y-краю площадки (y-175): шкив (Ø16) должен висеть в
# ОТКРЫТОЙ зоне за краем пада, иначе вал бьёт в тело площадки (z75..83). y=-162 →
# край шкива y-170 внутри от края пада -175 (зазор 5). Ремень CD = 240-162 = 78.
MOTOR_XY = (0.0, -162.0)       # ось мотора (ремень GT2 CD 78 до шестерни)
PAD_TOP_Z = 83.0               # верх площадки — низ ноги кронштейна
M4_XY = [(-22.0, -196.0), (-22.0, -216.0), (22.0, -196.0), (22.0, -216.0)]
M4_CLR = 4.5                   # прорезь под M4
M4_SLOT = 3.0                  # ±ход прорези по Y (радиально)
M4_HEAD = 8.5                  # Ø зенковки/кармана головки

# ---------- плита (нога + площадка мотора) ----------
PLATE_Z0, PLATE_Z1 = 83.0, 91.0        # 8 мм плита на площадке
PLATE_X = 70.0
PLATE_Y0, PLATE_Y1 = -248.0, -140.0    # от каретки (−240) до мотора (−162) + M3
RAIL_Z1 = 96.0                         # боковые рёбра-рельсы (жёсткость консоли мотора)

# ---------- корпус подшипников (Ø30) на (0,−240) ----------
BOSS_D = 30.0
BOSS_Z0, BOSS_Z1 = 78.0, 97.0          # тело корпуса
BRG_OD = 22.15                         # посадка 608ZZ (проверенная на этом принтере)
BRG_H = 7.0
BRG_LO_Z0 = 79.0                       # нижний 608: 79..86 (входит снизу)
BRG_HI_Z1 = 96.0                       # верхний 608: 89..96 (входит сверху)
SHAFT_RELIEF = 16.0                    # Ø расточки между подшипниками (вал Ø8 + зазор)

# ---------- мотор NEMA17 ----------
NEMA_PITCH = 15.5                      # M3 на квадрате 31×31
M3_CLR = 3.4
PILOT_D = 23.0                         # окно под буртик Ø22 + вал
FLANGE_Z0, FLANGE_Z1 = 83.0, 86.0      # плита-фланец мотора (мотор садится сверху)

SEG = 64


def _cyl(r, z0, z1, x=0.0, y=0.0, seg=SEG):
    h = z1 - z0
    m = trimesh.creation.cylinder(radius=r, height=h, sections=seg)
    m.apply_translation([x, y, (z0 + z1) / 2.0])
    return m


def _box(x0, x1, y0, y1, z0, z1):
    x0, x1 = sorted((x0, x1)); y0, y1 = sorted((y0, y1)); z0, z1 = sorted((z0, z1))
    m = trimesh.creation.box(extents=[x1 - x0, y1 - y0, z1 - z0])
    m.apply_translation([(x0 + x1) / 2.0, (y0 + y1) / 2.0, (z0 + z1) / 2.0])
    return m


def _slot_y(x, y, r, z0, z1, travel=M4_SLOT):
    """Прорезь вдоль Y (радиально): прямоугольный паз шир. 2r, ±travel по Y."""
    return _box(x - r, x + r, y - travel - r, y + travel + r, z0, z1)


def build():
    solids, cuts = [], []

    # --- плита: нога на площадку + фланец мотора, одно тело ---
    solids.append(_box(-PLATE_X / 2, PLATE_X / 2, PLATE_Y0, PLATE_Y1, PLATE_Z0, PLATE_Z1))

    # --- корпус подшипников на (0,−240): столбик Ø30, торчит вниз и вверх от плиты ---
    px, py = PINION_XY
    solids.append(_cyl(BOSS_D / 2, BOSS_Z0, BOSS_Z1, px, py))

    # боковые рёбра-рельсы по всей длине (жёсткость: мотор на консоли от болтов пада)
    for sx in (-1, 1):
        solids.append(_box(sx * (PLATE_X / 2 - 4), sx * PLATE_X / 2,
                           PLATE_Y0, PLATE_Y1, PLATE_Z0, RAIL_Z1))

    # === ВЫРЕЗЫ ===
    # 4 радиальные прорези M4 + карманы головок сверху
    for (x, y) in M4_XY:
        cuts.append(_slot_y(x, y, M4_CLR / 2, PLATE_Z0 - 1, PLATE_Z1 + 1))
        cuts.append(_slot_y(x, y, M4_HEAD / 2, PLATE_Z1 - 3.0, PLATE_Z1 + 1))

    # подшипники: нижний 608 снизу, верхний 608 сверху, между — расточка Ø16
    cuts.append(_cyl(BRG_OD / 2, BRG_LO_Z0, BRG_LO_Z0 + BRG_H, px, py))          # 79..86
    cuts.append(_cyl(BRG_OD / 2, BRG_HI_Z1 - BRG_H, BRG_HI_Z1, px, py))          # 89..96
    cuts.append(_cyl(SHAFT_RELIEF / 2, BOSS_Z0 - 1, BOSS_Z1 + 1, px, py))        # сквозной вал/расточка

    # мотор: окно под буртик+вал + 4×M3 (31×31)
    mx, my = MOTOR_XY
    cuts.append(_cyl(PILOT_D / 2, FLANGE_Z0 - 1, FLANGE_Z1 + 1, mx, my))
    for sx in (-1, 1):
        for sy in (-1, 1):
            cuts.append(_cyl(M3_CLR / 2, PLATE_Z0 - 1, PLATE_Z1 + 1,
                             mx + sx * NEMA_PITCH, my + sy * NEMA_PITCH))

    part = trimesh.boolean.union(solids)
    part = trimesh.boolean.difference([part] + cuts)

    # опустить на стол z=0 для печати (ориентацию выберешь в слайсере)
    part.apply_translation([0, 0, -part.bounds[0][2]])
    return part


if __name__ == "__main__":
    p = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    p.export(OUT)
    b0, b1 = p.bounds
    print(f"[OK] {OUT.name}: watertight={p.is_watertight}  vol={p.volume/1000:.1f} cm3")
    print(f"     габарит {b1[0]-b0[0]:.1f} × {b1[1]-b0[1]:.1f} × {b1[2]-b0[2]:.1f} мм")
