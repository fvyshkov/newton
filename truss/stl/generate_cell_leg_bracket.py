#!/usr/bin/env python3
"""
Скоба-ножка оправы (Cell_leg_bracket.stl) для truss-варианта 8" Newton.

Печатается 3 шт. Каждая защёлкивается на торце уха старой задней плиты
(Mirror_cell_back.stl) через её существующее радиальное Ø5.5мм отверстие
с помощью имеющегося болта M5×20 (или M5×16, если докупим). Скоба
спускается вниз с вертикальным сквозным отверстием Ø9мм под шпильку M8.

Геометрия привязки к существующей оправе:
  * Радиус оси радиального отверстия в ухе: r = 125мм (TUBE_R)
  * Z-координата радиального отверстия: z = 0 (середина плиты толщины 8мм)
  * Углы ушей: 30°, 150°, 270° (но генерим одну деталь — поворачивается
    при сборке)

Принцип крепления:
  * Болт M5 проходит ИЗНУТРИ оправы (со стороны центра ячейки) сквозь
    радиальное отверстие в ухе → в сквозное отверстие скобы → закручивается
    в M5 гайку, захваченную в гексагональном кармане на внешней грани скобы.
  * Стянутая пара: скоба прижимается внутренней гранью к цилиндрической
    наружной поверхности уха.
  * Внутри корпуса скобы — гексагональный карман на M5 hex гайку (S=8мм,
    толщина 4мм). Гайка ставится при сборке один раз, фиксируется на резьбу
    Loctite если нужно.

Высотная регулировка:
  * Снизу скобы — вертикальное сквозное отверстие Ø9мм (clearance под M8).
  * Шпилька M8×80 ввинчена в дно mirror box (или зафиксирована гайкой снизу).
  * Скоба сидит на M8 шпильке через clearance, опирается на нижнюю гайку
    (барашек) на шпильке. Опциональная гайка сверху фиксирует положение.
  * Ход регулировки = ход нижнего барашка по шпильке ≈ 30-40мм.

Печать:
  * Z = вертикаль скобы (по оси телескопа в сборке)
  * Печатать стоя (вертикально), чтобы M5 hole был перпендикулярен оси Z
    — это даёт ему лучшую круглость и резьбу гайки. Поддержки под
    нависающий M5 hole либо принтер с поддержкой, либо переориентировать.
  * 4-5 периметров, 30% gyroid, PETG-HF или ASA. Не PLA.
"""
import math
from pathlib import Path

import trimesh

# --- Привязка к существующей оправе ---
EAR_R = 125.0          # радиус наружной поверхности уха
PLATE_T = 8.0          # толщина задней плиты (z = -4 ... +4)
M5_HOLE_R = 2.75       # Ø5.5 clearance под M5

# --- Скоба ---
BRACKET_T = 14.0       # радиальная толщина (от ear edge r=125 до r=139)
BRACKET_W = 26.0       # тангенциальная ширина
BRACKET_H = 60.0       # вертикальная высота
WALL = 4.0             # min толщина стенок около отверстий

# Положения отверстий
M5_Z = 0.0             # M5 hole по высоте — на уровне середины уха

# M8 hole внизу — clearance под M8 шпильку
M8_HOLE_R = 4.6        # Ø9.2 clearance под M8 (некруглость печати)
M8_FROM_BOTTOM = 12.0  # от низа скобы до оси M8

# Карман под M5 hex гайку на ВНЕШНЕЙ грани скобы
NUT_AF = 8.0           # размер под ключ (across flats) для M5 hex
NUT_THICK = 4.5        # толщина гайки + запас
NUT_POCKET_DEPTH = 5.0 # глубина кармана (чуть больше толщины гайки)

# Вертикальное углубление под M8 шайбу/гайку сверху (опционально, фиксация)
TOP_WASHER_R = 8.0     # Ø16 углубление под M8 шайбу/барашек
TOP_WASHER_DEPTH = 2.0

# Концентрический выгиб внутренней грани скобы под цилиндр уха.
# Делается как вырез радиусом EAR_R, центром на оси телескопа,
# чтобы скоба плотно сидела на цилиндрическом торце уха.
INNER_CONCAVE = True

SEG = 96

OUT_DIR = Path(__file__).parent
OUT_FILE = OUT_DIR / "Cell_leg_bracket.stl"


def main():
    # Локальные координаты скобы:
    #   x — радиально (наружу от оси телескопа)
    #   y — тангенциально (вдоль ширины)
    #   z — вертикально (по оси телескопа)
    #
    # При сборке скоба будет повернута на угол уха (30°/150°/270°)
    # и сдвинута по радиусу.

    # Внутренняя грань скобы по умолчанию на x = 0 (r = EAR_R при сборке)
    # Внешняя грань на x = +BRACKET_T (r = EAR_R + BRACKET_T)
    # Вертикальный диапазон: z = -BRACKET_H + 4 ... +4
    # (верх скобы на 4мм выше плоскости задней плиты, низ — на 60-4=56мм ниже)

    z_top = PLATE_T / 2.0
    z_bot = z_top - BRACKET_H

    # Основной блок
    body = trimesh.creation.box(extents=(BRACKET_T, BRACKET_W, BRACKET_H))
    body.apply_translation([BRACKET_T / 2.0, 0.0, (z_top + z_bot) / 2.0])

    # Вогнутая внутренняя грань — вырезаем цилиндр радиуса EAR_R с центром
    # на оси телескопа (т.е. в локальных координатах при x = -EAR_R, y=0).
    if INNER_CONCAVE:
        ear_cyl = trimesh.creation.cylinder(
            radius=EAR_R,
            height=BRACKET_H * 2,
            sections=256,
        )
        ear_cyl.apply_translation([-EAR_R + 0.0, 0.0, (z_top + z_bot) / 2.0])
        # Хотим оставить тело СНАРУЖИ ear_cyl: subtract the cylinder.
        # Внутренняя грань станет вогнутой по радиусу EAR_R.
        body = body.difference(ear_cyl)

    # 1) Радиальное сквозное отверстие M5 (clearance) — ось X
    m5 = trimesh.creation.cylinder(
        radius=M5_HOLE_R,
        height=BRACKET_T * 3.0,
        sections=64,
    )
    rot_y = trimesh.transformations.rotation_matrix(math.radians(90), [0, 1, 0])
    m5.apply_transform(rot_y)
    m5.apply_translation([BRACKET_T / 2.0, 0.0, M5_Z])
    body = body.difference(m5)

    # 2) Карман под M5 hex гайку на внешней грани (x = BRACKET_T)
    # Гексагональная призма, ось X, расположена так чтобы её "наружная"
    # грань совпадала с x = BRACKET_T (вход кармана = внешняя грань скобы).
    hex_pocket = trimesh.creation.cylinder(
        radius=NUT_AF / math.cos(math.radians(30)) / 2.0,  # circumscribed для AF
        height=NUT_POCKET_DEPTH,
        sections=6,
    )
    # rotate so axis is X
    hex_pocket.apply_transform(rot_y)
    # центр кармана: глубина NUT_POCKET_DEPTH от внешней грани → центр на
    # x = BRACKET_T - NUT_POCKET_DEPTH/2
    hex_pocket.apply_translation(
        [BRACKET_T - NUT_POCKET_DEPTH / 2.0, 0.0, M5_Z]
    )
    body = body.difference(hex_pocket)

    # 3) Вертикальное сквозное отверстие M8 (clearance) — ось Z, у низа скобы
    # Радиально центрировано по середине толщины скобы (x = BRACKET_T/2),
    # чтобы шпилька шла строго вертикально и не упиралась в ухо.
    m8 = trimesh.creation.cylinder(
        radius=M8_HOLE_R,
        height=BRACKET_H * 2.0,
        sections=64,
    )
    m8.apply_translation([BRACKET_T / 2.0, 0.0, z_bot + M8_FROM_BOTTOM])
    body = body.difference(m8)

    # 4) Углубление сверху скобы (на верхней грани) под шайбу/барашек,
    # если ставить верхний фиксатор. Делаем легкое концентрическое
    # углубление вокруг M8 hole.
    top_washer = trimesh.creation.cylinder(
        radius=TOP_WASHER_R,
        height=TOP_WASHER_DEPTH * 2,
        sections=SEG,
    )
    # верх углубления = верх скобы; центр углубления = z_top - TOP_WASHER_DEPTH/2
    top_washer.apply_translation(
        [BRACKET_T / 2.0, 0.0, z_top - TOP_WASHER_DEPTH / 2.0 + 0.5]
    )
    body = body.difference(top_washer)

    body.export(OUT_FILE)
    e = body.extents
    print(f"  -> {OUT_FILE.name}  {len(body.faces)} faces, "
          f"{e[0]:.1f}x{e[1]:.1f}x{e[2]:.1f}mm")
    print()
    print("Что делать после печати:")
    print("  1. Печать 3 шт. Стоя (вертикально), 4-5 периметров,")
    print("     30% gyroid, PETG-HF или ASA.")
    print("  2. Вдавить M5 hex гайку в карман на внешней грани (одной")
    print("     каплей супер-клея зафиксировать).")
    print("  3. Поставить скобу к торцу уха задней плиты, продеть M5×20")
    print("     болт ИЗНУТРИ ячейки через старое радиальное отверстие в")
    print("     ухе → в сквозное отверстие скобы → закрутить в гайку.")
    print("  4. Шпильку M8×80 ввинтить в дно mirror box (резьбовой инсерт).")
    print("     Скоба надевается на шпильку через нижнее Ø9мм отверстие;")
    print("     барашек M8 снизу под скобой поддерживает её. Опционально")
    print("     барашек сверху фиксирует.")


if __name__ == "__main__":
    main()
